    /// <summary>
    /// Compares a provider's rendered SQL with its goldens file, whitespace and separators
    /// included, and writes the file when accepting. A goldens file is written only by its accept
    /// test: set NUCLEUS_ACCEPT_GOLDENS=1, run it, and review the diff. Update deliberately,
    /// never casually.
    /// </summary>
    public static class RawGoldens
    {
        public static void AssertMatches(IReadOnlyDictionary<string, Func<string>> cases, IReadOnlyDictionary<string, string> expected, string name)
        {
            Assert.True(expected.TryGetValue(name, out var golden), $"No golden for '{name}'. Accept the goldens to add it.");

            var actual = SqlSnapshot.NormalizeVariablesOnly(cases[name]());

            Assert.Equal(golden, actual);
        }

        public static void Accept(IReadOnlyDictionary<string, Func<string>> cases, string className)
        {
            Assert.SkipUnless(Environment.GetEnvironmentVariable("NUCLEUS_ACCEPT_GOLDENS") == "1",
                $"Set NUCLEUS_ACCEPT_GOLDENS=1 to regenerate {className}.cs from the current renderer.");

            var sb = new StringBuilder();
            sb.Append("namespace TFM.Nucleus.Tests\n{\n");
            sb.Append("    /// <summary>Generated by the raw golden tests' accept test. Do not edit by hand.</summary>\n");
            sb.Append($"    public static class {className}\n    {{\n");
            sb.Append("        public static IReadOnlyDictionary<string, string> Expected { get; } = new Dictionary<string, string>(StringComparer.Ordinal)\n        {\n");
            foreach (var name in cases.Keys.Order(StringComparer.Ordinal))
            {
                var text = SqlSnapshot.NormalizeVariablesOnly(cases[name]());
                sb.Append("            [").Append(Literal(name)).Append("] = ").Append(Literal(text)).Append(",\n");
            }
            sb.Append("        };\n    }\n}\n");

            File.WriteAllText(Path.Combine(TestSourceDirectory(), $"{className}.cs"), sb.ToString().Replace("\n", "\r\n"), new UTF8Encoding(true));
        }

        private static string Literal(string value)
        {
            var sb = new StringBuilder("\"");
            foreach (var c in value)
                sb.Append(c switch
                {
                    '"' => "\\\"",
                    '\\' => "\\\\",
                    '\n' => "\\n",
                    '\r' => "\\r",
                    '\t' => "\\t",
                    _ => c.ToString(),
                });
            return sb.Append('"').ToString();
        }

        /// <summary>The test project's source folder, found by walking up from the build output.</summary>
        internal static string TestSourceDirectory()
        {
            for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir != null; dir = dir.Parent)
                if (File.Exists(Path.Combine(dir.FullName, "TFM.Nucleus.Tests.csproj")))
                    return dir.FullName;
            throw new DirectoryNotFoundException("TFM.Nucleus.Tests.csproj was not found above the test output folder.");
        }
    }

    /// <summary>Pins the exact SQL Server text for every case in <see cref="SqlServerGoldenCorpus"/>.</summary>
    public class SqlServerRawGoldenTests
    {
        public static TheoryData<string> CaseNames() => new(SqlServerGoldenCorpus.Cases.Keys.Order(StringComparer.Ordinal));

        [Theory]
        [MemberData(nameof(CaseNames))]
        public void Rendered_MatchesGolden(string name) => RawGoldens.AssertMatches(SqlServerGoldenCorpus.Cases, SqlServerGoldens.Expected, name);

        [Fact]
        public void EveryGolden_HasACase() => Assert.Empty(SqlServerGoldens.Expected.Keys.Except(SqlServerGoldenCorpus.Cases.Keys));

        [Fact]
        public void Accept_WritesTheGoldensFile() => RawGoldens.Accept(SqlServerGoldenCorpus.Cases, nameof(SqlServerGoldens));
    }

