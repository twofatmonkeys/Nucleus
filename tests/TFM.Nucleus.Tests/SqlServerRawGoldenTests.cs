using System.Text;

namespace TFM.Nucleus.Tests
{
    /// <summary>
    /// Pins the exact SQL Server text, whitespace and separators included, for every case in
    /// <see cref="SqlServerGoldenCorpus"/>. The expected text lives in <see cref="SqlServerGoldens"/>,
    /// which only <see cref="Accept_WritesTheGoldensFile"/> writes: set NUCLEUS_ACCEPT_GOLDENS=1,
    /// run that one test, and review the diff. Update deliberately, never casually.
    /// </summary>
    public class SqlServerRawGoldenTests
    {
        public static TheoryData<string> CaseNames() => new(SqlServerGoldenCorpus.Cases.Keys.Order(StringComparer.Ordinal));

        [Theory]
        [MemberData(nameof(CaseNames))]
        public void Rendered_MatchesGolden(string name)
        {
            Assert.True(SqlServerGoldens.Expected.TryGetValue(name, out var expected), $"No golden for '{name}'. Accept the goldens to add it.");

            var actual = SqlSnapshot.NormalizeVariablesOnly(SqlServerGoldenCorpus.Cases[name]());

            Assert.Equal(expected, actual);
        }

        [Fact]
        public void EveryGolden_HasACase()
        {
            Assert.Empty(SqlServerGoldens.Expected.Keys.Except(SqlServerGoldenCorpus.Cases.Keys));
        }

        [Fact]
        public void Accept_WritesTheGoldensFile()
        {
            Assert.SkipUnless(Environment.GetEnvironmentVariable("NUCLEUS_ACCEPT_GOLDENS") == "1",
                "Set NUCLEUS_ACCEPT_GOLDENS=1 to regenerate SqlServerGoldens.cs from the current renderer.");

            var sb = new StringBuilder();
            sb.Append("namespace TFM.Nucleus.Tests\n{\n");
            sb.Append("    /// <summary>Generated by SqlServerRawGoldenTests.Accept_WritesTheGoldensFile. Do not edit by hand.</summary>\n");
            sb.Append("    public static class SqlServerGoldens\n    {\n");
            sb.Append("        public static IReadOnlyDictionary<string, string> Expected { get; } = new Dictionary<string, string>(StringComparer.Ordinal)\n        {\n");
            foreach (var name in SqlServerGoldenCorpus.Cases.Keys.Order(StringComparer.Ordinal))
            {
                var text = SqlSnapshot.NormalizeVariablesOnly(SqlServerGoldenCorpus.Cases[name]());
                sb.Append("            [").Append(Literal(name)).Append("] = ").Append(Literal(text)).Append(",\n");
            }
            sb.Append("        };\n    }\n}\n");

            File.WriteAllText(Path.Combine(TestSourceDirectory(), "SqlServerGoldens.cs"), sb.ToString().Replace("\n", "\r\n"), new UTF8Encoding(true));
        }

        private static string Literal(string value)
        {
            var sb = new StringBuilder("\"");
            foreach (var c in value)
                sb.Append(c switch
                {
                    '"' => "\\\"",
                    '\\' => "\\\\",
                    '\n' => "\\n",
                    '\r' => "\\r",
                    '\t' => "\\t",
                    _ => c.ToString(),
                });
            return sb.Append('"').ToString();
        }

        /// <summary>The test project's source folder, found by walking up from the build output.</summary>
        internal static string TestSourceDirectory()
        {
            for (var dir = new DirectoryInfo(AppContext.BaseDirectory); dir != null; dir = dir.Parent)
                if (File.Exists(Path.Combine(dir.FullName, "TFM.Nucleus.Tests.csproj")))
                    return dir.FullName;
            throw new DirectoryNotFoundException("TFM.Nucleus.Tests.csproj was not found above the test output folder.");
        }
    }
}
