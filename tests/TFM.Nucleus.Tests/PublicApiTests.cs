using System.Reflection;
using System.Text;

namespace TFM.Nucleus.Tests
{
    /// <summary>
    /// The public surface of every shipping assembly, one line per type and member, compared
    /// with <see cref="PublicApiSnapshot"/>. A change to what consumers can reach is a review
    /// decision: accept it with NUCLEUS_ACCEPT_GOLDENS=1 and the diff shows exactly what moved.
    /// </summary>
    public class PublicApiTests
    {
        public static IEnumerable<Assembly> ShippingAssemblies() =>
        [
            typeof(IDataProvider).Assembly,                              // TFM.Nucleus.Abstractions
            typeof(CoreObject).Assembly,                                 // TFM.Nucleus
            typeof(ObjectDataManager).Assembly,                          // TFM.Nucleus.Data
            typeof(SQLDataProvider).Assembly,                            // TFM.Nucleus.Data.SQL
            typeof(TFM.Nucleus.Bindery.NucleusBinderyStore).Assembly,
            typeof(TFM.Nucleus.S3Library.NucleusS3AssetStore).Assembly,
            typeof(TFM.Nucleus.Stencil.NucleusTemplateStore).Assembly,
            typeof(TFM.Nucleus.Attribution.NucleusAttributionStore).Assembly,
        ];

        public static TheoryData<string> AssemblyNames() => new(ShippingAssemblies().Select(a => a.GetName().Name!));

        [Theory]
        [MemberData(nameof(AssemblyNames))]
        public void PublicSurface_MatchesSnapshot(string assemblyName)
        {
            var assembly = ShippingAssemblies().Single(a => a.GetName().Name == assemblyName);
            Assert.True(PublicApiSnapshot.Surfaces.TryGetValue(assemblyName, out var expected), $"No snapshot for {assemblyName}.");

            var actual = Describe(assembly);

            Assert.Equal(expected, actual);
        }

        [Fact]
        public void Accept_WritesTheSnapshotFile()
        {
            Assert.SkipUnless(Environment.GetEnvironmentVariable("NUCLEUS_ACCEPT_GOLDENS") == "1",
                "Set NUCLEUS_ACCEPT_GOLDENS=1 to regenerate PublicApiSnapshot.cs from the current assemblies.");

            var sb = new StringBuilder();
            sb.Append("namespace TFM.Nucleus.Tests\n{\n");
            sb.Append("    /// <summary>Generated by PublicApiTests.Accept_WritesTheSnapshotFile. Do not edit by hand.</summary>\n");
            sb.Append("    public static class PublicApiSnapshot\n    {\n");
            sb.Append("        public static IReadOnlyDictionary<string, string[]> Surfaces { get; } = new Dictionary<string, string[]>(StringComparer.Ordinal)\n        {\n");
            foreach (var assembly in ShippingAssemblies())
            {
                sb.Append("            [\"").Append(assembly.GetName().Name).Append("\"] =\n            [\n");
                foreach (var line in Describe(assembly))
                    sb.Append("                \"").Append(line.Replace("\\", "\\\\").Replace("\"", "\\\"")).Append("\",\n");
                sb.Append("            ],\n");
            }
            sb.Append("        };\n    }\n}\n");

            File.WriteAllText(Path.Combine(SqlServerRawGoldenTests.TestSourceDirectory(), "PublicApiSnapshot.cs"), sb.ToString().Replace("\n", "\r\n"), new UTF8Encoding(true));
        }

        private const BindingFlags Declared =
            BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;

        /// <summary>Every exported type and every member a consumer can reach, sorted.</summary>
        public static string[] Describe(Assembly assembly)
        {
            var lines = new List<string>();
            foreach (var type in assembly.GetExportedTypes())
            {
                lines.Add($"{Kind(type)} {Name(type)}{BaseList(type)}");
                foreach (var member in type.GetMembers(Declared).Where(IsVisible))
                    lines.Add($"  {Name(type)}::{Describe(member)}");
            }
            return [.. lines.Order(StringComparer.Ordinal)];
        }

        private static bool IsVisible(MemberInfo member) => member switch
        {
            MethodBase m => !m.IsSpecialName || m.Name.StartsWith("op_", StringComparison.Ordinal) || m is ConstructorInfo
                ? m.IsPublic || m.IsFamily || m.IsFamilyOrAssembly
                : false,
            FieldInfo f => f.IsPublic || f.IsFamily || f.IsFamilyOrAssembly,
            PropertyInfo p => p.GetAccessors(nonPublic: true).Any(a => a.IsPublic || a.IsFamily || a.IsFamilyOrAssembly),
            EventInfo e => e.AddMethod is { } add && (add.IsPublic || add.IsFamily || add.IsFamilyOrAssembly),
            Type t => t.IsNestedPublic || t.IsNestedFamily || t.IsNestedFamORAssem,
            _ => false,
        };

        private static string Kind(Type type) =>
            type.IsInterface ? "interface"
            : type.IsEnum ? "enum"
            : type.IsValueType ? "struct"
            : typeof(Delegate).IsAssignableFrom(type) ? "delegate"
            : type.IsAbstract && type.IsSealed ? "static class"
            : type.IsAbstract ? "abstract class"
            : type.IsSealed ? "sealed class"
            : "class";

        private static string BaseList(Type type)
        {
            var bases = new List<string>();
            if (type.BaseType is { } b && b != typeof(object) && b != typeof(ValueType) && b != typeof(Enum) && !typeof(Delegate).IsAssignableFrom(type))
                bases.Add(Name(b));
            bases.AddRange(type.GetInterfaces().Where(i => i.IsPublic || i.IsNestedPublic).Select(Name).Order(StringComparer.Ordinal));
            return bases.Count == 0 ? "" : " : " + string.Join(", ", bases);
        }

        private static string Describe(MemberInfo member) => member switch
        {
            ConstructorInfo c => $"{Access(c)}.ctor({Parameters(c)})",
            MethodInfo m => $"{Access(m)}{(m.IsStatic ? "static " : "")}{(m.IsAbstract ? "abstract " : m.IsVirtual && !m.IsFinal ? "virtual " : "")}{Name(m.ReturnType)} {m.Name}{Generics(m)}({Parameters(m)})",
            FieldInfo f => $"{Access(f)}{(f.IsStatic ? "static " : "")}{(f.IsLiteral ? "const " : f.IsInitOnly ? "readonly " : "")}{Name(f.FieldType)} {f.Name}",
            PropertyInfo p => $"{Name(p.PropertyType)} {p.Name}{Indexer(p)} {{{Accessor(p.GetMethod, "get")}{Accessor(p.SetMethod, "set")} }}",
            EventInfo e => $"event {Name(e.EventHandlerType!)} {e.Name}",
            Type t => $"nested {Kind(t)} {Name(t)}",
            _ => member.ToString()!,
        };

        private static string Access(MethodBase m) => m.IsPublic ? "public " : "protected ";

        private static string Access(FieldInfo f) => f.IsPublic ? "public " : "protected ";

        private static string Accessor(MethodInfo? accessor, string name) =>
            accessor is null || !(accessor.IsPublic || accessor.IsFamily || accessor.IsFamilyOrAssembly) ? ""
            : $" {(accessor.IsPublic ? "" : "protected ")}{(accessor.IsStatic ? "static " : "")}{name};";

        private static string Indexer(PropertyInfo p) =>
            p.GetIndexParameters() is { Length: > 0 } ps ? $"[{string.Join(", ", ps.Select(x => Name(x.ParameterType)))}]" : "";

        private static string Generics(MethodInfo m) =>
            m.IsGenericMethodDefinition ? $"<{string.Join(", ", m.GetGenericArguments().Select(a => a.Name))}>" : "";

        private static string Parameters(MethodBase m) =>
            string.Join(", ", m.GetParameters().Select(p => $"{(p.IsOut ? "out " : p.ParameterType.IsByRef ? "ref " : "")}{Name(p.ParameterType)}{(p.HasDefaultValue ? " = ..." : "")}"));

        private static string Name(Type type)
        {
            if (type.IsByRef)
                return Name(type.GetElementType()!);
            if (type.IsGenericParameter)
                return type.Name;
            if (type.IsArray)
                return Name(type.GetElementType()!) + "[]";
            var name = type.IsNested ? $"{Name(type.DeclaringType!)}+{type.Name}" : $"{type.Namespace}.{type.Name}";
            if (!type.IsGenericType)
                return name;
            var tick = name.IndexOf('`');
            var args = type.GetGenericArguments();
            return $"{(tick < 0 ? name : name[..tick])}<{string.Join(", ", args.Select(Name))}>";
        }
    }
}
